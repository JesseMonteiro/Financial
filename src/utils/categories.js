/** Hex tint for a category key (defaults when custom color missing). */
export function getCategoryTint(raw, categories = []) {
  return resolveCategoryColor(raw, categories)
    || DEFAULT_PURCHASE_CATEGORIES.find((c) => c.key === (resolveCategoryKind(raw) || 'Other'))?.color
    || '#64748b';
}

export function slugifyCategoryKey(label, existingKeys = []) {
  const words = String(label || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-zA-Z0-9\s]/g, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  let base = words
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join('') || 'Category';
  if (/^[0-9]/.test(base)) base = `Cat${base}`;
  const used = new Set((existingKeys || []).map((k) => String(k).toLowerCase()));
  if (!used.has(base.toLowerCase())) return base;
  let i = 2;
  while (used.has(`${base}${i}`.toLowerCase())) i += 1;
  return `${base}${i}`;
}

/**
 * Returns Level 1 categories from Pluggy.
 * Level 1 categories have no parentId and match top-level categories.
 */
export function pluggyCategoryOptions(categories = []) {
  const list = Array.isArray(categories) ? categories : [];
  const level1 = list.filter((c) => {
    if (!c) return false;
    const hasParent = Boolean(c.parentId || c.parent_id || c.parentDescription);
    if (hasParent) return false;
    const desc = c.description || '';
    if (PLUGGY_TO_KIND[desc] && PLUGGY_TO_KIND[desc] !== desc) {
      return false;
    }
    return true;
  });

  return level1
    .map((c) => {
      const desc = c.description || '';
      const label = (desc === 'Food and drinks' || desc === 'Food' || c.descriptionTranslated === 'Comida e bebidas')
        ? 'Alimentação'
        : (c.descriptionTranslated || translateCategory(desc) || desc || String(c.id || ''));
      return {
        value: String(c.id || c.key || ''),
        label,
        isBase: true,
      };
    })
    .filter((opt) => opt.value)
    .sort((a, b) => a.label.localeCompare(b.label, 'pt-BR'));
}

